#!/usr/bin/env python3
"""Build ACK programs (the compiler passes) as Minix programs for the rosco.

	mkpass.py [-n] name=target ...

target is a program in the host build of ACK (ack/.obj/..., see
build-ack.sh), e.g. cpp.ansi=.obj/lang/cem/cpp.ansi/+cpp.ansi/cpp.ansi.
For each one this reads the link command from ack/.obj/build.ninja, and for
every object in it (also the members of the module libraries .a) the
compile command: the source file (often generated by the host build) and
its -I/-D flags.  passlib/*.c (functions the Minix 2.0.4 libc lacks, such
as strdup) go into pass/obj/passlib.a, linked before the libc.  It writes pass/build.sh, which compiles them with
m68k-elf-gcc -mshort and the Minix headers into pass/obj/, archives the
libraries with m68k-elf-ar, links with crtso.o and the rosco libc
(../lib) and converts the result with ../tools/mkminix.py into
pass/bin/name.  build.sh is then run once in the rosco toolchain
container (../xrun); -n only writes it.

The host build's sandboxes only limit which files a step can see, so the
compiles run from the ACK root with the same paths.  This is a host
program (it needs ninja).
"""
import os
import re
import shlex
import subprocess
import sys

here = os.path.dirname(os.path.abspath(__file__))
ack = os.path.join(here, "ack")
rosco = os.path.dirname(here)
out = os.path.join(here, "pass")
inc = os.path.join(rosco, "include")
minixinc = os.path.join(os.path.dirname(os.path.dirname(rosco)), "include")
passinc = os.path.join(here, "passinc")

CROSS = ("m68k-elf-gcc -mcpu=68010 -mshort -Os -std=gnu99 -fno-builtin "
         "-fno-common -fno-strict-aliasing -fno-delete-null-pointer-checks "
         "-Werror=implicit-function-declaration -Werror=int-conversion "
         "-include %s/rosco_sizeof.h -include %s/passcompat.h "
         "-D_EM_WSIZE=2 -D_EM_PSIZE=4 "
         "-D_EM_LSIZE=4 -D__m68000=1 -D__minix=1 -D__MSHORT__ -D_MINIX "
         "-D_POSIX_SOURCE -I%s -I%s -I%s" % (inc, passinc, passinc, inc, minixinc))
LDFLAGS = "m68k-elf-gcc -mcpu=68010 -mshort -nostdlib -T %s/tools/prog.ld -Wl,--emit-relocs" % rosco


# heap and stack (the gap between bss and stack, as chmem sets it)
STACKS = {"em_cemcom.ansi": "256k", "ncg": "128k", "em_opt": "128k",
          "as": "128k", "em_led": "128k", "cpp.ansi": "96k",
          "ack": "32k", "aal": "48k", "cv": "32k"}


def single(target):
    """The last command of the build edge for target."""
    r = subprocess.run(["ninja", "-f", ".obj/build.ninja", "-t", "commands",
                        "-s", target], cwd=ack, capture_output=True,
                       text=True, check=True)
    cmd = r.stdout.strip().splitlines()[-1]
    w = cmd.split()
    if len(w) == 2 and w[0] == "sh" and w[1].endswith(".sh"):
        # long commands are kept in a rule-*.sh file, one step per line
        with open(os.path.join(ack, w[1])) as f:
            cmd = "&&".join(l for l in f.read().splitlines()
                            if l.strip() and l.strip() != "set -e")
    return cmd


def inner(cmd, tool):
    """The words of the step that runs tool, inside the sandbox command."""
    for part in cmd.split("&&"):
        part = part.strip().lstrip("(").rstrip(")").strip()
        w = shlex.split(part)
        if w and w[0] in tool:
            return w
    sys.exit("mkpass: no %s step in: %s" % (tool, cmd[:300]))


def objname(path):
    return os.path.join(out, "obj", path.replace(".obj/", "", 1))


def compile_step(o, lines):
    w = inner(single(o), ("cc", "gcc"))
    src = None
    flags = []
    i = 1
    while i < len(w):
        a = w[i]
        if a in ("-c",):
            pass
        elif a == "-o":
            i += 1
        elif a.startswith("-I") or a.startswith("-D"):
            if a.startswith("-DUNREACHABLE_CODE"):
                a = "-DUNREACHABLE_CODE=__builtin_unreachable()"
            flags.append(a)
        elif a.startswith("-"):
            pass			# host options (-g, -Os, -Werror=...)
        else:
            src = a
        i += 1
    if src is None:
        sys.exit("mkpass: no source for " + o)
    dst = objname(o)
    lines.append("mkdir -p %s" % shlex.quote(os.path.dirname(dst)))
    lines.append("%s %s -c -o %s %s" % (CROSS, " ".join(shlex.quote(f) for f in flags),
                                       shlex.quote(dst), shlex.quote(src)))
    return dst


def archive_step(a, lines, done):
    if a in done:
        return done[a]
    w = inner(single(a), ("ar",))
    members = [m for m in w[3:] if m.endswith(".o")]
    objs = [compile_step(m, lines) for m in members]
    dst = objname(a)
    lines.append("mkdir -p %s && rm -f %s" % (shlex.quote(os.path.dirname(dst)), shlex.quote(dst)))
    lines.append("m68k-elf-ar cqs %s %s" % (shlex.quote(dst), " ".join(shlex.quote(o) for o in objs)))
    done[a] = dst
    return dst


def program(name, target, lines, done):
    w = inner(single(target), ("cc", "gcc"))
    objs, libs = [], []
    for a in w[1:]:
        if a.endswith(".o"):
            objs.append(compile_step(a, lines))
        elif a.endswith(".a"):
            libs.append(archive_step(a, lines, done))
    elf = os.path.join(out, "obj", name + ".elf")
    lines.append("%s -o %s %s/lib/crtso.o %s -Wl,--start-group %s %s %s/lib/libc.a -Wl,--end-group"
                 % (LDFLAGS, elf, rosco, " ".join(objs), " ".join(libs),
                    os.path.join(out, "obj", "passlib.a"), rosco))
    lines.append("mkdir -p %s/bin && python3 %s/tools/mkminix.py -q -S %s %s %s/bin/%s"
                 % (out, rosco, STACKS.get(name, "64k"), elf, out, name))


def main():
    args = sys.argv[1:]
    dry = args[:1] == ["-n"]
    if dry:
        args = args[1:]
    if not args:
        sys.exit("usage: mkpass.py [-n] name=target ...")
    lines = ["set -e", "cd %s" % shlex.quote(ack)]
    done = {}
    plib = os.path.join(out, "obj", "passlib.a")
    pobjs = []
    for c in sorted(os.listdir(os.path.join(here, "passlib"))):
        if c.endswith(".c"):
            o = os.path.join(out, "obj", "passlib", c[:-2] + ".o")
            lines.append("mkdir -p %s" % os.path.dirname(o))
            lines.append("%s -c -o %s %s" % (CROSS, o, os.path.join(here, "passlib", c)))
            pobjs.append(o)
    lines.append("rm -f %s && m68k-elf-ar cqs %s %s" % (plib, plib, " ".join(pobjs)))
    for a in args:
        name, target = a.split("=", 1)
        program(name, target, lines, done)
    os.makedirs(out, exist_ok=True)
    script = os.path.join(out, "build.sh")
    with open(script, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("mkpass: %s, %d commands" % (script, len(lines)))
    if not dry:
        subprocess.run([os.path.join(rosco, "xrun"), "sh", script], cwd=here, check=True)


main()
